const {test,expect}=require('@playwright/test');
const origin='http://127.0.0.1:3100';
const session=(name)=>({name:'vsph.portal.sid',value:name,url:origin,httpOnly:true,sameSite:'Lax'});
test('employee scheduler saves, edits, filters and deletes actual events; customer stays isolated',async({page,context},info)=>{
 test.skip(!process.env.PROJECT_E2E_DATABASE,'Requires isolated native PostgreSQL');
 test.setTimeout(90000);
 await context.addCookies([session('fixture-hrms-staff-'+info.project.name)]);
 await page.goto('/dashboard');
 await expect(page.locator('#employeeCalendar')).toBeVisible();
 await expect(page.locator('#calendarPeriod')).toContainText(/\d{4}/);
 await expect(page.locator('#calendarGrid .calendar-month')).toBeVisible();
 await page.locator('#calendarNew').click();
 await expect(page.locator('#calendarDialog')).toBeVisible();
 const form=page.locator('#calendarForm');
 const title='Calendar delivery '+info.project.name;
 await form.locator('[name=title]').fill(title);
 await form.locator('[name=description]').fill('Planning');
 await form.locator('[name=startAt]').fill('2026-11-18T09:00');
 await form.locator('[name=endAt]').fill('2026-11-18T10:00');
 await form.locator('[name=scope]').selectOption('personal');
 await form.locator('[name=color]').selectOption('green');
 await form.locator('[name=tags]').fill('Work, Planning');
 await form.locator('#calendarSave').click();
 await expect(page.locator('#calendarDialog')).toBeHidden();
 await expect(page.locator('.calendar-event').filter({hasText:title})).toHaveCount(1);
 await page.reload();
 await expect(page.locator('.calendar-event').filter({hasText:title})).toHaveCount(1);
 await page.locator('[data-calendar-view=list]').click();
 await expect(page.locator('.calendar-list')).toBeVisible();
 await page.locator('#calendarFilterColor').selectOption('red');
 await expect(page.locator('.calendar-event')).toHaveCount(0);
 await page.locator('#calendarFilterColor').selectOption('green');
 await expect(page.locator('.calendar-event').filter({hasText:title})).toHaveCount(1);
 await page.locator('.calendar-event').filter({hasText:title}).click();
 await form.locator('[name=title]').fill(title+' updated');
 await form.locator('#calendarSave').click();
 await expect(page.locator('.calendar-event').filter({hasText:title+' updated'})).toHaveCount(1);
 await page.locator('.calendar-event').filter({hasText:title+' updated'}).click();
 page.once('dialog',dialog=>dialog.accept());
 await form.locator('#calendarDelete').click();
 await expect(page.locator('.calendar-event').filter({hasText:title+' updated'})).toHaveCount(0);
 await page.locator('[data-calendar-view=week]').click();
 await expect(page.locator('.calendar-week-grid')).toBeVisible();
 await page.locator('[data-calendar-view=day]').click();
 await expect(page.locator('.calendar-day-grid')).toBeVisible();
 await context.clearCookies();await context.addCookies([session('fixture-music-customer-session')]);
 const response=await context.request.get('/api/hrms/calendar?from=2026-11-01T00%3A00%3A00.000Z&to=2026-12-01T00%3A00%3A00.000Z');
 expect(response.status()).toBe(403);
 await page.goto('/dashboard');await expect(page.locator('#employeeCalendar')).toBeHidden();
});
